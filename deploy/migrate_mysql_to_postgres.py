"""One-time migration from the two former MySQL databases to empty PostgreSQL databases."""

import argparse
from collections import defaultdict
from datetime import date, datetime
from decimal import Decimal
from hashlib import sha256
import json
import os
import re
import sys
from zoneinfo import ZoneInfo

import psycopg
from psycopg import sql
from psycopg.rows import dict_row
import pymysql


IDENTIFIER = re.compile(r"[a-zA-Z_][a-zA-Z_0-9]*")
MYSQL_DATABASES = {"opentools": "opentools", "yougo": "laoyouba"}
MASK = (1 << 256) - 1
SHANGHAI = ZoneInfo("Asia/Shanghai")


def qualified(identifier):
    if not IDENTIFIER.fullmatch(identifier):
        raise ValueError("unexpected SQL identifier in source schema")
    return "`" + identifier + "`"


def source_query(db, command, params=()):
    with db.cursor(pymysql.cursors.DictCursor) as cursor:
        cursor.execute(command, params)
        return [{key.lower(): value for key, value in row.items()} for row in cursor.fetchall()]


def new_type(row):
    datatype = row["data_type"]
    if datatype in {"varchar", "char"}:
        return f"varchar({int(row['character_maximum_length'])})"
    if datatype in {"enum", "json", "text", "mediumtext", "longtext"}:
        return "text"
    if datatype in {"int", "integer", "bigint"}:
        return "bigint" if datatype == "bigint" or "unsigned" in row["column_type"] else "integer"
    if datatype in {"tinyint", "smallint"}:
        return "integer" if "unsigned" in row["column_type"] and datatype == "smallint" else "smallint"
    if datatype == "decimal":
        return f"numeric({int(row['numeric_precision'])},{int(row['numeric_scale'])})"
    if datatype == "datetime":
        return f"timestamp({int(row['datetime_precision'] or 0)})"
    if datatype == "date":
        return "date"
    raise ValueError("unexpected MySQL data type: " + datatype)


def definition(column):
    name = sql.Identifier(column["column_name"])
    parts = [name, sql.SQL(new_type(column))]
    value = column["column_default"]
    if "auto_increment" in column["extra"]:
        parts.append(sql.SQL("GENERATED BY DEFAULT AS IDENTITY"))
    elif value is not None:
        if re.fullmatch(r"current_timestamp(?:\(\d*\))?", str(value), flags=re.I):
            parts.append(sql.SQL("DEFAULT CURRENT_TIMESTAMP"))
        else:
            parts += [sql.SQL("DEFAULT"), sql.Literal(str(value))]
    if column["is_nullable"] == "NO":
        parts.append(sql.SQL("NOT NULL"))
    return sql.SQL(" ").join(parts)


def create_indexes(pg, table, indexes):
    for index in indexes:
        names = sql.SQL(", ").join(sql.Identifier(row["column_name"]) for row in index)
        table_name = sql.Identifier(table)
        name = index[0]["index_name"]
        if name == "PRIMARY":
            pg.execute(sql.SQL("ALTER TABLE {} ADD PRIMARY KEY ({})").format(table_name, names))
            continue
        columns = []
        for row in index:
            col = sql.Identifier(row["column_name"])
            if row["sub_part"]:
                col = sql.SQL("left({}, {})").format(col, sql.Literal(int(row["sub_part"])))
            if row["collation"] == "D":
                col = sql.SQL("{} DESC").format(col)
            columns.append(col)
        # MySQL index names are per table and PostgreSQL index names are per schema.
        suffix = sha256((table + ":" + name).encode()).hexdigest()[:12]
        title = sql.Identifier(f"{table[:41]}_{suffix}")
        unique = sql.SQL("UNIQUE ") if not index[0]["non_unique"] else sql.SQL("")
        pg.execute(sql.SQL("CREATE {}INDEX {} ON {} ({})").format(
            unique, title, table_name, sql.SQL(", ").join(columns),
        ))


def update_timestamps(pg, table, columns):
    body = []
    for column in columns:
        name = sql.Identifier(column["column_name"]).as_string(pg)
        if "on update CURRENT_TIMESTAMP" in column["extra"]:
            body.append(f"IF NEW.{name} IS NOT DISTINCT FROM OLD.{name} THEN NEW.{name} := CURRENT_TIMESTAMP; END IF;")
    if not body:
        return
    name = sql.Identifier(f"touch_{table}")
    pg.execute(sql.SQL("CREATE FUNCTION {}() RETURNS trigger AS {} LANGUAGE plpgsql").format(
        name, sql.Literal("BEGIN " + " ".join(body) + " RETURN NEW; END"),
    ))
    pg.execute(sql.SQL("CREATE TRIGGER touch_timestamp BEFORE UPDATE ON {} FOR EACH ROW EXECUTE FUNCTION {}()").format(
        sql.Identifier(table), name,
    ))


def convert(value, type_name, nullable):
    if type_name in {"timestamp with time zone", "timestamp without time zone", "date"} and isinstance(value, str):
        if value.startswith("0000-") and nullable:
            return None
        raise ValueError("unsupported date from source database")
    if value is not None and type_name == "boolean":
        return bool(value)
    if isinstance(value, datetime) and type_name == "timestamp with time zone":
        return value.replace(tzinfo=SHANGHAI)
    return value


def normalized(value):
    if isinstance(value, datetime):
        if value.tzinfo is not None:
            value = value.astimezone(SHANGHAI).replace(tzinfo=None)
        return value.isoformat(timespec="microseconds")
    if isinstance(value, date):
        return value.isoformat()
    if isinstance(value, Decimal):
        return str(value.normalize())
    return value


def hash_row(row):
    data = json.dumps([normalized(value) for value in row], ensure_ascii=False, separators=(",", ":")).encode()
    return int.from_bytes(sha256(data).digest(), "big")


def copy_table(mysql, pg, table, columns, target_columns):
    source_names = ", ".join(qualified(col["column_name"]) for col in columns)
    pg_names = sql.SQL(", ").join(sql.Identifier(col["column_name"]) for col in columns)
    command = sql.SQL("COPY {} ({}) FROM STDIN").format(sql.Identifier(table), pg_names)
    count, digest = 0, 0
    converters = [
        (target_columns[col["column_name"]]["data_type"], col["is_nullable"] == "YES")
        for col in columns
    ]
    with mysql.cursor(pymysql.cursors.SSCursor) as src, pg.cursor() as target:
        src.execute(f"SELECT {source_names} FROM {qualified(table)}")
        with target.copy(command) as writer:
            for row in src:
                values = tuple(convert(value, dtype, nullable) for value, (dtype, nullable) in zip(row, converters))
                writer.write_row(values)
                digest = (digest + hash_row(values)) & MASK
                count += 1
    actual_count, actual_digest = 0, 0
    with pg.cursor(name="verify_" + table) as cursor:
        cursor.execute(sql.SQL("SELECT {} FROM {}").format(pg_names, sql.Identifier(table)))
        for row in cursor:
            actual_count += 1
            actual_digest = (actual_digest + hash_row(row)) & MASK
    if (actual_count, actual_digest) != (count, digest):
        raise ValueError(f"row or checksum mismatch in {table}")
    for column in columns:
        if "auto_increment" not in column["extra"]:
            continue
        key = column["column_name"]
        sequence = pg.execute("SELECT pg_get_serial_sequence(%s, %s)", (table, key)).fetchone()[0]
        if sequence is None:
            raise ValueError(f"identity missing on {table}.{key}")
        highest = pg.execute(sql.SQL("SELECT max({}) FROM {}").format(sql.Identifier(key), sql.Identifier(table))).fetchone()[0]
        if highest is not None:
            pg.execute("SELECT setval(%s::regclass, %s, true)", (sequence, highest))
    print(f"{table}: {count} rows, checksum verified", flush=True)


def run(source, target_env):
    source_schema = MYSQL_DATABASES[source]
    with pymysql.connect(
        host=os.environ["MIGRATE_MYSQL_HOST"], port=int(os.environ["MIGRATE_MYSQL_PORT"]),
        user=os.environ["MIGRATE_MYSQL_USER"], password=os.environ["MIGRATE_MYSQL_PASSWORD"],
        database=source_schema, charset="utf8mb4", connect_timeout=8, read_timeout=180,
    ) as mysql, psycopg.connect(os.environ[target_env]) as pg:
        with mysql.cursor() as cursor:
            cursor.execute("SET SESSION time_zone = '+08:00'")
            cursor.execute("SET SESSION TRANSACTION ISOLATION LEVEL REPEATABLE READ")
            cursor.execute("START TRANSACTION WITH CONSISTENT SNAPSHOT, READ ONLY")
        pg.execute("SELECT pg_advisory_xact_lock(82422402)")
        pg.execute("SET LOCAL TIME ZONE 'Asia/Shanghai'")
        tables = source_query(mysql, """
            SELECT table_name FROM information_schema.tables
            WHERE table_schema=%s AND table_type='BASE TABLE' ORDER BY table_name
            """, (source_schema,))
        all_columns = defaultdict(list)
        for row in source_query(mysql, """
            SELECT table_name, column_name, LOWER(data_type) AS data_type, column_type, column_default,
                extra, is_nullable, character_maximum_length, numeric_precision, numeric_scale, datetime_precision
            FROM information_schema.columns WHERE table_schema=%s ORDER BY table_name, ordinal_position
            """, (source_schema,)):
            all_columns[row["table_name"]].append(row)
        indexes = defaultdict(lambda: defaultdict(list))
        for row in source_query(mysql, """
            SELECT TABLE_NAME AS table_name, INDEX_NAME AS index_name, COLUMN_NAME AS column_name,
                NON_UNIQUE AS non_unique, SUB_PART AS sub_part, COLLATION AS collation, INDEX_TYPE AS index_type
            FROM information_schema.statistics WHERE table_schema=%s ORDER BY table_name, index_name, seq_in_index
            """, (source_schema,)):
            if row["index_type"] != "BTREE" or row["column_name"] is None:
                raise ValueError("non-B-tree or expression index requires explicit translation")
            indexes[row["table_name"]][row["index_name"]].append(row)
        new_tables = []
        for row in tables:
            table = row["table_name"]
            print(f"Copying {table}", flush=True)
            columns = all_columns[table]
            identifier = sql.Identifier(table)
            exists = pg.execute("SELECT to_regclass(%s)", (table,)).fetchone()[0]
            if exists:
                if pg.execute(sql.SQL("SELECT EXISTS(SELECT 1 FROM {})").format(identifier)).fetchone()[0]:
                    raise ValueError("refusing to change a populated destination table")
            else:
                pg.execute(sql.SQL("CREATE TABLE {} ({})").format(identifier, sql.SQL(", ").join(map(definition, columns))))
                new_tables.append(table)
            with pg.cursor(row_factory=dict_row) as cursor:
                cursor.execute("""
                    SELECT column_name, data_type FROM information_schema.columns
                    WHERE table_schema=current_schema() AND table_name=%s
                    """, (table,))
                target_cols = {col["column_name"]: col for col in cursor}
            if set(col["column_name"] for col in columns) - target_cols.keys():
                raise ValueError(f"destination schema does not have all source columns in {table}")
            copy_table(mysql, pg, table, columns, target_cols)
        for table in new_tables:
            create_indexes(pg, table, indexes[table].values())
            update_timestamps(pg, table, all_columns[table])
        references = defaultdict(list)
        for row in source_query(mysql, """
            SELECT u.table_name, u.constraint_name, u.column_name, u.referenced_table_name,
                u.referenced_table_schema, u.referenced_column_name, r.update_rule, r.delete_rule
            FROM information_schema.key_column_usage u JOIN information_schema.referential_constraints r
              ON u.constraint_schema=r.constraint_schema AND u.table_name=r.table_name AND u.constraint_name=r.constraint_name
            WHERE u.table_schema=%s AND u.referenced_table_name IS NOT NULL
            ORDER BY u.table_name, u.constraint_name, u.ordinal_position
            """, (source_schema,)):
            if row["referenced_table_schema"] != source_schema:
                raise ValueError("cross-database foreign key requires explicit migration")
            references[(row["table_name"], row["constraint_name"])].append(row)
        for (table, name), rows in references.items():
            choices = {"CASCADE", "RESTRICT", "NO ACTION", "SET NULL", "SET DEFAULT"}
            update, delete = rows[0]["update_rule"], rows[0]["delete_rule"]
            if update not in choices or delete not in choices:
                raise ValueError("unknown foreign key action")
            pg.execute(sql.SQL("ALTER TABLE {} ADD CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({}) ON UPDATE {} ON DELETE {}").format(
                sql.Identifier(table), sql.Identifier(name),
                sql.SQL(", ").join(sql.Identifier(row["column_name"]) for row in rows),
                sql.Identifier(rows[0]["referenced_table_name"]),
                sql.SQL(", ").join(sql.Identifier(row["referenced_column_name"]) for row in rows),
                sql.SQL(update), sql.SQL(delete),
            ))
        print(f"{source}: verified all {len(tables)} tables before commit", flush=True)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("source", choices=MYSQL_DATABASES)
    parser.add_argument("target_env", help="Name of the environment variable containing the PostgreSQL DSN")
    args = parser.parse_args()
    try:
        run(args.source, args.target_env)
    except (pymysql.MySQLError, psycopg.Error) as error:
        # SQL diagnostics may contain row contents or credentials.
        print(f"Migration failed and rolled back: {type(error).__name__} ({getattr(error, 'sqlstate', '')})", file=sys.stderr)
        sys.exit(1)
