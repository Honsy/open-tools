// EnsureIntros fills a site introduction only when the field is still empty,
// so later edits in the admin are left alone.
func EnsureIntros(db *gorm.DB) error {
	var links []models.Link
	if err := db.Where("body = ? OR body IS NULL", "").Find(&links).Error; err != nil {
		return err
	}
	for i := range links {
		body, ok := intros[links[i].Name]
		if !ok || body == "" {
			continue
		}
		if err := db.Model(&links[i]).Update("body", body).Error; err != nil {
			return err
		}
	}
	return nil
}

